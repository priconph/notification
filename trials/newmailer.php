	function sendTaskReminder($subj, $det, $rec, $stat,$edate,$sdate) {
	$newLine = "\r\n";
	$emailstat="";
	if($stat="On-Going"){
	$emailstat="This is an on going task that started ".$sdate." and its due on ".$edate."";
	}
	else if($stat="Overdue"){
	$emailstat="This task is already overdue it started ".$sdate." and its was due on ".$edate."";
	}
	

		$to = $rec;
		$bcc = '';
		$from = '';

		$subject = $subj;
		$body  = $det .$newLine;
		$body  .= $newLine;
		$body .=  $newLine;
		$body .=  $newLine;
		$body .=  $emailstat.$newLine;
		$body .=  $newLine;
		$body .=  "This E-mail is automatically generated by the Alert Notification System.".$newLine;
		$body .=  "Don't reply to this e-mail, this is only a reminder created by the system, Thank you!";
					
		$headers = "MIME-Version: 1.0" ;
		$headers .= "Content-Type: text/html; charset = \"UTF-8\";\n";
		$headers .= "From: <".$from.">";
		$headers .= "To: <".$to.">";
		$headers .= "Bcc: <".$bcc.">";
		$headers .= "Subject: <".$subject.">";
		
		global $SmtpServer;
		global $SmtpPort;
		global $SmtpUser;
		global $SmtpPass;
		$SMTPMail = new SMTPClient ($SmtpServer, $SmtpPort, $SmtpUser, $SmtpPass, $from, $to, $bcc, $subject, $body,$headers);
		$SMTPChat = $SMTPMail->SendMail();
		
	}
