	function sendTaskReminder($subj, $det, $to,$cc,$stat,$edate,$sdate) {
		$newLine = "\r\n";
		$today=date('Y/m/d');
		$emailstat="This task started on ".$sdate." and was due on ".$edate;

		$subject = "Task Reopen!";
		$body  =  "The task \"".$subj."\" has now been Reopened.".$newLine;
		$body  .= "This might be due to an incomplete task or the Cancellation was clicked accidentally. ";
		$body  .= "This task reopening date: ".$today;
		$body .=  $newLine;
		$body .=  $newLine;
		$body .=  $emailstat.$newLine;
		$body .=  $newLine;
		$body .=  "The system sends notifications at 12am.".$newLine;
		$body .=  "This E-mail is automatically generated by the Alert Notification System.".$newLine;
		$body .=  "Don't reply to this e-mail, this is only a reminder created by the system, Thank you!";

		$mail = new PHPMailer();
		//to recipients
		$recip=explode(",",$to);
		for($i=0; $i<sizeof($recip); $i++){
			$mail->AddAddress($recip[$i]);
		}
		
		//cc recipients
		$cc=explode(",",$cc);
		for($i=0; $i<sizeof($cc); $i++){
			$mail->AddCC($cc[$i]);
		}
		$mail->AddBCC('jgsulit@pricon.ph');
		$mail->SetFrom('issinfoservice@pricon.ph', 'Alert Notification System');
		$mail->Subject = $subject;
		$mail->Body = $body;
		$mail->Send();		
	}
	
	
		
		
